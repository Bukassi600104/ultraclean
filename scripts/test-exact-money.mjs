import assert from 'node:assert/strict';
import {load} from './load-pure-typescript.mjs';
const {calculateFarmFinance}=load('lib/farm-finance-calculations.ts');
const {sumMoney,subtractMoney,moneyNumber}=load('lib/money.ts');
assert.equal(sumMoney(['999999999999999999.01','0.09']),'999999999999999999.10');
assert.equal(subtractMoney('+1','+0.1'),'0.9');
assert.equal(moneyNumber('-0.005'),-0.01);assert.equal(moneyNumber('1e-7'),0);
const date='2026-10-27',blank={transfers:[],expenses:[],feed:[],sales:[]};
const finance=rows=>calculateFarmFinance({...blank,...rows},{date,from:'2026-10-01',to:date});
assert.equal(finance({sales:[{date,total_amount:'0.1'},{date,total_amount:'0.2'}]}).revenue,0.3,'sum decimal values exactly');
assert.equal(finance({feed:[{date,cost:'2716231.9999999'}]}).closing_balance,-2716232,'round only final output');
assert.equal(finance({sales:[{date,total_amount:'0.004'},{date,total_amount:'0.004'}]}).revenue,0.01,'do not round each historical row');
assert.equal(finance({feed:[{date,cost:'1.005'}]}).closing_balance,-1.01,'negative ties round away from zero');
assert.throws(()=>finance({sales:[{date,total_amount:'9999999999999999.99'}]}),/range|precision/i,'never silently lose cents');
for(const total_amount of [null,undefined,'',NaN,'bad'])assert.throws(()=>finance({sales:[{date,total_amount}]}),/amount|decimal/i,'invalid saved money is not zero');
const bridge=finance({transfers:[{date:'2026-09-30',amount:'0.004'},{date,amount:'0.004'}]});
assert.equal(bridge.period_reconciliation.closing_owner_balance,0.01);
assert.equal(bridge.period_reconciliation.owner_rounding_adjustment,0.01,'make displayed bridge rounding explicit');
const {summarizeUltraTidy,summarizeProperties,summarizeContent}=load('lib/ceo-calculations.ts');
const scope={from:date,to:date};
const u=summarizeUltraTidy({inflow:[{date,amount:'0.1',service:'cleaning'},{date,amount:'0.2',service:'cleaning'}],expenses:[]},scope);
assert.equal(u.revenue,0.3);assert.equal(u.income_breakdown[0].value,0.3);
const p=summarizeProperties({properties:[],units:[],maintenance:[],rent:[{payment_date:date,amount:'0.1',currency:'CAD'},{payment_date:date,amount:'0.2',currency:'CAD'}],expenses:[{expense_date:date,amount:'0.4',currency:'CAD'}]},scope);
assert.deepEqual(p.finances,[{currency:'CAD',rent:0.3,expenses:0.4,net:-0.1}]);
const c=summarizeContent({records:[],performance:[],leads:[],sales:[{sale_date:date,amount:'0.1',currency:'CAD',sale_type:'affiliate'},{sale_date:date,amount:'0.2',currency:'CAD',sale_type:'affiliate'}]},scope);
assert.equal(c.sales[0].affiliate,0.3);assert.equal(c.sales_by_content[0].value,0.3);
console.log('PASS exact money: decimal sums, legacy scale, negatives, rounding bridge, invalid/large amounts and cross-app currency ledgers');
